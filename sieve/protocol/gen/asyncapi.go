package gen

import (
	"fmt"

	"sieve/sieve/protocol"
)

// AsyncAPI renders the two WebSocket wires as an AsyncAPI 3.0 document.
//
// Actions are written from the SERVER's point of view, as AsyncAPI 3 defines
// them: the app "receives" what a client sends and "sends" what a client
// receives. The Markdown reference states the same thing the other way round for
// the reader writing a client.
func (g *Generator) AsyncAPI() ([]byte, error) {
	channels := newYAMLMap()
	operations := newYAMLMap()
	messages := newYAMLMap()

	for _, channel := range g.contract.Channels() {
		address, err := g.contract.ChannelAddress(channel)
		if err != nil {
			return nil, err
		}
		channelMessages := newYAMLMap()
		for _, direction := range g.contract.Directions() {
			var names []string
			for _, f := range g.contract.FramesFor(channel, direction) {
				name := g.messageName(f)
				message, err := g.message(f)
				if err != nil {
					return nil, err
				}
				messages.Set(name, message)
				channelMessages.Set(name, newYAMLMap().Set("$ref", "#/components/messages/"+name))
				names = append(names, name)
			}
			if len(names) == 0 {
				continue
			}
			operations.Set(string(channel)+g.actionSuffix(direction), g.operationFor(channel, direction, names))
		}

		entry := newYAMLMap().
			Set("address", address).
			Set("title", string(channel)+" channel")
		if params := g.contract.PathParams(address); len(params) > 0 {
			// Declared, not described: the placeholder is read off the route, and
			// nothing in the contract writes prose about it — inventing some here
			// would be the one thing this generator must never do.
			parameters := newYAMLMap()
			for _, p := range params {
				parameters.Set(p, newYAMLMap())
			}
			entry.Set("parameters", parameters)
		}
		entry.Set("messages", channelMessages)
		channels.Set(string(channel), entry)
	}

	doc := newYAMLMap()
	doc.Set("asyncapi", "3.0.0")
	doc.Set("info", newYAMLMap().
		Set("title", "Sieve WebSocket contract").
		Set("version", "1.0.0").
		Set("description", g.asyncAPIDescription()))
	doc.Set("channels", channels)
	doc.Set("operations", operations)
	doc.Set("components", newYAMLMap().
		Set("messages", messages).
		Set("schemas", g.componentSchemas(g.frameSchemaRoots())).
		Set("correlationIds", g.correlationIDs()))
	return g.encode(doc)
}

// frameSchemaRoots names the payload types the two wires carry.
func (g *Generator) frameSchemaRoots() []string {
	var roots []string
	for _, f := range g.contract.Frames {
		if name := g.schemas.Name(f.Payload); name != "" {
			roots = append(roots, name)
		}
	}
	return roots
}

func (g *Generator) asyncAPIDescription() string {
	return "The document and workspace WebSocket wires, generated by " + generatedBy + " from sieve/protocol.\n" +
		"Descriptions are the godoc comments and doc: struct tags on the declarations themselves.\n" +
		"Actions are written from the server's point of view: receive is client-to-server."
}

func (g *Generator) actionSuffix(d protocol.Direction) string {
	if d == protocol.Inbound {
		return "Receive"
	}
	return "Send"
}

func (g *Generator) operationFor(channel protocol.Channel, direction protocol.Direction, names []string) *yamlMap {
	action := "receive"
	summary := "Frames the server accepts on the " + string(channel) + " channel."
	if direction == protocol.Outbound {
		action = "send"
		summary = "Frames the server emits on the " + string(channel) + " channel."
	}
	refs := make([]*yamlMap, 0, len(names))
	for _, name := range names {
		refs = append(refs, newYAMLMap().Set("$ref", "#/channels/"+string(channel)+"/messages/"+name))
	}
	return newYAMLMap().
		Set("action", action).
		Set("channel", newYAMLMap().Set("$ref", "#/channels/"+string(channel))).
		Set("summary", summary).
		Set("messages", refs)
}

// message describes one frame. Its title is the type WORD, because that word is
// what the frame carries in its `type` field and what a dispatcher keys on.
func (g *Generator) message(f protocol.FrameEntry) (*yamlMap, error) {
	schema, err := g.schemas.Add(f.Payload)
	if err != nil {
		return nil, fmt.Errorf("frame %q on the %s channel: %w", f.Type, f.Channel, err)
	}
	out := newYAMLMap().
		Set("name", f.Type).
		Set("title", f.Type).
		Set("summary", g.docs.Summary(g.frameDoc(f))).
		Set("description", g.frameDoc(f)).
		Set("contentType", "application/json")
	if field := g.correlationField(f); field != "" {
		out.Set("correlationId", newYAMLMap().Set("$ref", "#/components/correlationIds/"+field))
	}
	out.Set("payload", schema.YAML())
	return out, nil
}

// correlationIds declares the two request/reply conventions the wires use. The
// document wire mints an opId per request and echoes it on the reply; the
// workspace wire carries a correlationId per command, and a command's several
// lifecycle results all carry the same one.
func (g *Generator) correlationIDs() *yamlMap {
	out := newYAMLMap()
	for _, c := range []struct{ field, description string }{
		{"opId", "The client mints an opId on a document-wire request; the server echoes it on the reply, and an unsolicited frame carries none."},
		{"correlationId", "A workspace-wire command carries a correlationId; every result for that command echoes it, and the reply goes back to the socket that asked."},
	} {
		if !g.usesCorrelationField(c.field) {
			continue
		}
		out.Set(c.field, newYAMLMap().
			Set("description", c.description).
			Set("location", "$message.payload#/"+c.field))
	}
	return out
}

func (g *Generator) usesCorrelationField(field string) bool {
	for _, f := range g.contract.Frames {
		if g.correlationField(f) == field {
			return true
		}
	}
	return false
}
