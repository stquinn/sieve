package gen

import (
	"fmt"
	"reflect"
	"sort"
	"strings"

	"sieve/sieve/protocol"
)

// OpenAPI renders the typed HTTP surface as an OpenAPI 3.1 document.
//
// It describes the TYPED endpoints only. The rest of the app's routes serve
// hypermedia or bytes, whose contract is the template or the file — putting them
// here would claim a schema they do not have; they are inventoried in the
// Markdown reference instead.
func (g *Generator) OpenAPI() ([]byte, error) {
	paths := newYAMLMap()
	for _, path := range g.endpointPaths() {
		item := newYAMLMap()
		for _, e := range g.endpointsAt(path) {
			operation, err := g.operation(e)
			if err != nil {
				return nil, err
			}
			item.Set(strings.ToLower(e.Method), operation)
		}
		paths.Set(path, item)
	}

	doc := newYAMLMap()
	doc.Set("openapi", "3.1.0")
	doc.Set("info", newYAMLMap().
		Set("title", "Sieve HTTP contract").
		Set("version", "1.0.0").
		Set("description", g.openAPIDescription()))
	doc.Set("paths", paths)
	roots, err := g.endpointSchemaRoots()
	if err != nil {
		return nil, err
	}
	doc.Set("components", newYAMLMap().Set("schemas", g.componentSchemas(roots)))
	return g.encode(doc)
}

func (g *Generator) openAPIDescription() string {
	return "The typed JSON endpoints, generated by " + generatedBy + " from sieve/protocol.\n" +
		"Descriptions are the godoc comments and doc: struct tags on the declarations themselves.\n" +
		"Routes serving hypermedia or bytes are deliberately absent: their contract is the\n" +
		"template they render, and " + APIMarkdownPath + " inventories them."
}

// endpointPaths returns each distinct path once, sorted — OpenAPI groups
// operations under the path, not the method.
func (g *Generator) endpointPaths() []string {
	seen := map[string]bool{}
	var paths []string
	for _, e := range g.contract.Endpoints {
		if !seen[e.Path] {
			seen[e.Path] = true
			paths = append(paths, e.Path)
		}
	}
	sort.Strings(paths)
	return paths
}

func (g *Generator) endpointsAt(path string) []protocol.EndpointEntry {
	var out []protocol.EndpointEntry
	for _, e := range g.contract.SortedEndpoints() {
		if e.Path == path {
			out = append(out, e)
		}
	}
	return out
}

func (g *Generator) operation(e protocol.EndpointEntry) (*yamlMap, error) {
	out := newYAMLMap()
	out.Set("operationId", g.operationID(e))
	out.Set("summary", g.docs.Summary(g.typeDoc(e.Request)))
	out.Set("description", g.typeDoc(e.Request))

	var fields []Field
	if e.Request != nil {
		var err error
		fields, err = g.schemas.Fields(e.Request)
		if err != nil {
			return nil, fmt.Errorf("endpoint %s %s: %w", e.Method, e.Path, err)
		}
	}

	parameters, body, err := g.parameters(e, fields)
	if err != nil {
		return nil, err
	}
	if len(parameters) > 0 {
		out.Set("parameters", parameters)
	}
	if body != nil {
		out.Set("requestBody", body)
	}

	responses := newYAMLMap()
	switch e.ResponseKind {
	case protocol.ResponseJSON:
		schema, err := g.schemas.Add(e.Response)
		if err != nil {
			return nil, err
		}
		responses.Set("200", newYAMLMap().
			Set("description", g.responseKindProse(e.ResponseKind)).
			Set("content", newYAMLMap().Set("application/json",
				newYAMLMap().Set("schema", schema.YAML()))))
	case protocol.ResponseFragment:
		responses.Set("200", newYAMLMap().
			Set("description", g.responseKindProse(e.ResponseKind)).
			Set("content", newYAMLMap().Set("text/html",
				newYAMLMap().Set("schema", newYAMLMap().Set("type", "string")))))
	default:
		responses.Set("204", newYAMLMap().Set("description", g.responseKindProse(e.ResponseKind)))
	}
	out.Set("responses", responses)
	return out, nil
}

// parameters splits a request struct into the places its fields actually travel:
// the route pattern's {name} placeholders are path parameters, a field tagged
// query:"…" is a query parameter, and what is left is the JSON body. The struct
// describes every parameter in one place, and the tags say which is which.
//
// The body is a $ref to the request type's component only when NOTHING was split
// off it — that is the case where the component and the body describe the same
// shape. A split type's body is written inline instead, because a component
// carrying the query parameter as a required body property would contradict the
// very operation that referenced it.
func (g *Generator) parameters(e protocol.EndpointEntry, fields []Field) ([]*yamlMap, *yamlMap, error) {
	var parameters []*yamlMap
	for _, name := range g.contract.PathParams(e.Path) {
		parameters = append(parameters, newYAMLMap().
			Set("name", name).
			Set("in", "path").
			Set("required", true).
			Set("schema", newYAMLMap().Set("type", "string")))
	}

	var bodyFields []Field
	for _, f := range fields {
		if f.Query == "" {
			bodyFields = append(bodyFields, f)
			continue
		}
		parameters = append(parameters, newYAMLMap().
			Set("name", f.Query).
			Set("in", "query").
			Set("required", f.Required).
			Set("description", f.Doc).
			Set("schema", f.Schema.YAML()))
	}
	body := g.schemas.ObjectSchema(bodyFields)

	if len(body.Properties) == 0 {
		return parameters, nil, nil
	}
	if len(bodyFields) == len(fields) {
		if name := g.schemas.Name(e.Request); name != "" {
			body = &Schema{Ref: "#/components/schemas/" + name}
		}
	}

	// The same schema in each encoding the handler reads: one contract, two
	// costumes, which is what AcceptsForm records.
	content := newYAMLMap().Set("application/json", newYAMLMap().Set("schema", body.YAML()))
	if e.AcceptsForm {
		content.Set("application/x-www-form-urlencoded", newYAMLMap().Set("schema", body.YAML()))
	}
	return parameters, newYAMLMap().
		Set("required", true).
		Set("content", content), nil
}

// operationID names an operation stably: method plus path with its separators
// and placeholders folded away, so a generated client's method names do not
// change when an unrelated endpoint is added.
func (g *Generator) operationID(e protocol.EndpointEntry) string {
	id := strings.ToLower(e.Method)
	word := false
	for _, r := range e.Path {
		switch r {
		case '/', '{', '}', '-', '.':
			word = true
			continue
		}
		if word {
			id += strings.ToUpper(string(r))
			word = false
			continue
		}
		id += string(r)
	}
	return id
}

// endpointSchemaRoots names the types the HTTP surface actually describes: every
// response, plus every request that travels wholly in the body.
//
// A request whose fields are SPLIT between the query string and the body earns no
// component. Its component would be a shape no message ever has — the operation
// says uuid is a query parameter, the component would say it is a required body
// property — and an unreferenced component that contradicts the operation beside
// it is worse than an absent one. Its body is written inline by parameters().
func (g *Generator) endpointSchemaRoots() ([]string, error) {
	var roots []string
	for _, e := range g.contract.Endpoints {
		if name := g.schemas.Name(e.Response); name != "" {
			roots = append(roots, name)
		}
		split, err := g.requestIsSplit(e.Request)
		if err != nil {
			return nil, fmt.Errorf("endpoint %s %s: %w", e.Method, e.Path, err)
		}
		if split {
			continue
		}
		if name := g.schemas.Name(e.Request); name != "" {
			roots = append(roots, name)
		}
	}
	return roots, nil
}

// requestIsSplit reports whether any of a request type's fields travels outside
// the body.
func (g *Generator) requestIsSplit(t reflect.Type) (bool, error) {
	if t == nil {
		return false, nil
	}
	fields, err := g.schemas.Fields(t)
	if err != nil {
		return false, err
	}
	for _, f := range fields {
		if f.Query != "" {
			return true, nil
		}
	}
	return false, nil
}

// componentSchemas emits the named schemas reachable from roots, sorted.
func (g *Generator) componentSchemas(roots []string) *yamlMap {
	schemas := newYAMLMap()
	for _, name := range g.schemas.Reachable(roots) {
		schemas.Set(name, g.schemas.Component(name).YAML())
	}
	return schemas
}

func (g *Generator) encode(doc *yamlMap) ([]byte, error) {
	body, err := doc.Encode()
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("# generated by %s — edit the declarations in sieve/protocol, not this file\n", generatedBy)
	return append([]byte(header), body...), nil
}
