package gen

import (
	"fmt"
	"reflect"
	"strings"

	"sieve/sieve/protocol"
)

// APIMarkdown renders the human-readable contract: what each wire carries, what
// each typed endpoint takes and answers, and — as an appendix — every route the
// app mounts, whether or not its contract is typed.
func (g *Generator) APIMarkdown() ([]byte, error) {
	var b strings.Builder

	b.WriteString("# Sieve API contract\n\n")
	b.WriteString(fmt.Sprintf("<!-- generated by %s — edit the declarations, not this file -->\n\n", generatedBy))
	b.WriteString("This file is generated from `sieve/protocol` and the assembled router.\n")
	b.WriteString("Every description below is a godoc comment or a `doc:\"…\"` struct tag read out of\n")
	b.WriteString("the source, so the way to change this document is to change the declaration it\n")
	b.WriteString("describes and run `go generate ./sieve/protocol`.\n\n")
	if intro := g.docs.Package(g.contract.DeclaredIn); intro != "" {
		b.WriteString(g.docs.Summary(intro))
		b.WriteString("\n\n")
	}

	if err := g.writeChannels(&b); err != nil {
		return nil, err
	}
	g.writeTopics(&b)
	if err := g.writeFrameReference(&b); err != nil {
		return nil, err
	}
	if err := g.writeEndpoints(&b); err != nil {
		return nil, err
	}
	if err := g.writePayloadTypes(&b); err != nil {
		return nil, err
	}
	g.writeCommands(&b)
	g.writeRouteInventory(&b)

	return []byte(b.String()), nil
}

func (g *Generator) writeChannels(b *strings.Builder) error {
	b.WriteString("## WebSocket channels\n\n")
	if doc := g.docs.Type(g.contract.DeclaredIn, "Channel"); doc != "" {
		b.WriteString(g.docs.Summary(doc))
		b.WriteString("\n\n")
	}
	for _, channel := range g.contract.Channels() {
		address, err := g.contract.ChannelAddress(channel)
		if err != nil {
			return err
		}
		b.WriteString(fmt.Sprintf("### `%s` — `%s`\n\n", channel, address))
		for _, direction := range g.contract.Directions() {
			frames := g.contract.FramesFor(channel, direction)
			if len(frames) == 0 {
				continue
			}
			b.WriteString(fmt.Sprintf("**%s**\n\n", g.directionTitle(direction)))
			b.WriteString("| Type | Payload | Correlated on | Purpose |\n")
			b.WriteString("|---|---|---|---|\n")
			for _, f := range frames {
				correlation := g.correlationField(f)
				if correlation != "" {
					correlation = "`" + correlation + "`"
				} else {
					correlation = "—"
				}
				b.WriteString(fmt.Sprintf("| `%s` | `%s` | %s | %s |\n",
					f.Type, f.Payload.String(), correlation,
					g.cell(g.docs.Summary(g.frameDoc(f)))))
			}
			b.WriteString("\n")
		}
	}
	return nil
}

// directionTitle names a direction from the CLIENT's point of view, which is who
// reads this document to write a client.
func (g *Generator) directionTitle(d protocol.Direction) string {
	if d == protocol.Inbound {
		return "Client → server"
	}
	return "Server → client"
}

func (g *Generator) writeTopics(b *strings.Builder) {
	if len(g.contract.Topics) == 0 {
		return
	}
	b.WriteString("## Invalidation topics\n\n")
	if doc := g.docs.Type(g.contract.DeclaredIn, "Topic"); doc != "" {
		b.WriteString(g.docs.Summary(doc))
		b.WriteString("\n\n")
	}
	b.WriteString("| Topic | Meaning |\n|---|---|\n")
	for _, t := range g.contract.Topics {
		b.WriteString(fmt.Sprintf("| `%s` | %s |\n", t, g.cell(g.docs.ConstValue(g.contract.DeclaredIn, string(t)))))
	}
	b.WriteString("\n")
}

func (g *Generator) writeFrameReference(b *strings.Builder) error {
	b.WriteString("## Frame reference\n\n")
	for _, channel := range g.contract.Channels() {
		b.WriteString(fmt.Sprintf("### `%s` channel\n\n", channel))
		for _, direction := range g.contract.Directions() {
			for _, f := range g.contract.FramesFor(channel, direction) {
				b.WriteString(fmt.Sprintf("#### `%s` — %s\n\n", f.Type, strings.ToLower(g.directionTitle(direction))))
				if doc := g.frameDoc(f); doc != "" {
					b.WriteString(g.docs.Summary(doc))
					b.WriteString("\n\n")
				}
				fields, err := g.schemas.Fields(f.Payload)
				if err != nil {
					return fmt.Errorf("frame %q: %w", f.Type, err)
				}
				g.writeFieldTable(b, fields)
			}
		}
	}
	return nil
}

func (g *Generator) writeFieldTable(b *strings.Builder, fields []Field) {
	if len(fields) == 0 {
		return
	}
	b.WriteString("| Field | Go type | Required | Description |\n|---|---|---|---|\n")
	for _, f := range fields {
		required := "no"
		if f.Required {
			required = "yes"
		}
		description := f.Doc
		// A doc: tag on a query field usually says so itself; the note is added only
		// when it does not, so the same fact is never stated twice in one cell.
		if f.Query != "" && !strings.Contains(description, "query parameter") {
			description = strings.TrimSpace(description + " (sent as the `" + f.Query + "` query parameter, not in the body)")
		}
		b.WriteString(fmt.Sprintf("| `%s` | `%s` | %s | %s |\n",
			f.JSONName, f.GoType, required, g.cell(description)))
	}
	b.WriteString("\n")
}

func (g *Generator) writeEndpoints(b *strings.Builder) error {
	b.WriteString("## Typed HTTP endpoints\n\n")
	b.WriteString("An endpoint appears here when its contract is typed data in either direction.\n")
	b.WriteString("Everything else the app serves is hypermedia or bytes, and appears in the route\n")
	b.WriteString("inventory below instead.\n\n")

	endpoints := g.contract.SortedEndpoints()
	b.WriteString("| Operation | Response | Purpose |\n|---|---|---|\n")
	for _, e := range endpoints {
		purpose := g.docs.Summary(g.typeDoc(e.Request))
		if purpose == "" {
			purpose = g.docs.Summary(g.typeDoc(e.Response))
		}
		b.WriteString(fmt.Sprintf("| `%s %s` | %s | %s |\n", e.Method, e.Path, e.ResponseKind, g.cell(purpose)))
	}
	b.WriteString("\n")

	for _, e := range endpoints {
		b.WriteString(fmt.Sprintf("### `%s %s`\n\n", e.Method, e.Path))
		if params := g.contract.PathParams(e.Path); len(params) > 0 {
			names := make([]string, 0, len(params))
			for _, p := range params {
				names = append(names, "`"+p+"`")
			}
			b.WriteString(fmt.Sprintf("Path parameters: %s\n\n", strings.Join(names, ", ")))
		}
		if e.Request != nil {
			b.WriteString(fmt.Sprintf("**Request** — `%s`\n\n", e.Request.String()))
			if e.AcceptsForm {
				b.WriteString("Accepts `application/json` or `application/x-www-form-urlencoded`, " +
					"under the same field names.\n\n")
			}
			if doc := g.typeDoc(e.Request); doc != "" {
				b.WriteString(g.docs.Summary(doc))
				b.WriteString("\n\n")
			}
			fields, err := g.schemas.Fields(e.Request)
			if err != nil {
				return fmt.Errorf("endpoint %s %s: %w", e.Method, e.Path, err)
			}
			g.writeFieldTable(b, fields)
		}
		if e.Response == nil {
			b.WriteString(fmt.Sprintf("**Response** — %s.\n\n", g.responseKindProse(e.ResponseKind)))
		} else {
			b.WriteString(fmt.Sprintf("**Response** — `%s`\n\n", e.Response.String()))
			if doc := g.typeDoc(e.Response); doc != "" {
				b.WriteString(g.docs.Summary(doc))
				b.WriteString("\n\n")
			}
			fields, err := g.schemas.Fields(e.Response)
			if err != nil {
				return fmt.Errorf("endpoint %s %s: %w", e.Method, e.Path, err)
			}
			g.writeFieldTable(b, fields)
		}
	}
	return nil
}

func (g *Generator) responseKindProse(kind protocol.ResponseKind) string {
	if doc := g.docs.ConstValue(g.contract.DeclaredIn, string(kind)); doc != "" {
		return doc
	}
	return string(kind)
}

// endpointTypeNames lists every request and response type, which is what the
// endpoints section above already describes. It is deliberately NOT
// openapi.go's endpointSchemaRoots: that one omits a split request because a
// component for it would contradict the operation, while this one must still
// count it, or the endpoints section and the payload-types section would both
// describe the same struct.
func (g *Generator) endpointTypeNames() []string {
	var names []string
	for _, e := range g.contract.Endpoints {
		for _, t := range []reflect.Type{e.Request, e.Response} {
			if name := g.schemas.Name(t); name != "" {
				names = append(names, name)
			}
		}
	}
	return names
}

// writePayloadTypes documents the types a frame or an endpoint REFERENCES —
// the block and domain values that cross the wire inside an envelope, and the
// envelopes' embedded parts. They carry their descriptions on their own
// declarations, in packages that know nothing about the wire, and this is where
// those descriptions are published.
func (g *Generator) writePayloadTypes(b *strings.Builder) error {
	roots := map[string]bool{}
	for _, name := range append(g.frameSchemaRoots(), g.endpointTypeNames()...) {
		roots[name] = true
	}

	var supporting []NamedType
	for _, named := range g.schemas.NamedTypes() {
		if !roots[named.Name] {
			supporting = append(supporting, named)
		}
	}
	if len(supporting) == 0 {
		return nil
	}

	b.WriteString("## Payload types\n\n")
	b.WriteString("Types a frame or an endpoint carries inside its envelope. Each is described on\n")
	b.WriteString("its own declaration, in the package that owns it.\n\n")
	for _, named := range supporting {
		b.WriteString(fmt.Sprintf("### `%s`\n\n", named.Type.String()))
		if doc := g.typeDoc(named.Type); doc != "" {
			b.WriteString(g.docs.Summary(doc))
			b.WriteString("\n\n")
		}
		if named.Type.Kind() != reflect.Struct {
			continue
		}
		fields, err := g.schemas.Fields(named.Type)
		if err != nil {
			return fmt.Errorf("payload type %s: %w", named.Type, err)
		}
		g.writeFieldTable(b, fields)
	}
	return nil
}

func (g *Generator) writeCommands(b *strings.Builder) {
	if len(g.contract.Commands) == 0 {
		return
	}
	b.WriteString("## Command words\n\n")
	b.WriteString("Every registered verb. They ride the workspace wire's `command` frame as DATA —\n")
	b.WriteString("a new command is not a new frame type — and are listed because a client has to\n")
	b.WriteString("spell both the verb and the family it is invoked within: the dispatcher rejects\n")
	b.WriteString("a verb sent under a family that is not its own.\n\n")
	b.WriteString("| Family | Command | Purpose |\n|---|---|---|\n")
	for _, c := range g.contract.Commands {
		b.WriteString(fmt.Sprintf("| `%s` | `/%s` | %s |\n", c.Family, c.Name, g.cell(c.Description)))
	}
	b.WriteString("\n")
}

func (g *Generator) writeRouteInventory(b *strings.Builder) {
	b.WriteString("## Route inventory\n\n")
	b.WriteString("Every route the app mounts, walked off the assembled router. `/ui/*` is safe,\n")
	b.WriteString("idempotent views and bytes; `/api/*` is operations and protocols. A route whose\n")
	b.WriteString("contract is typed data is described above; the rest serve hypermedia, bytes,\n")
	b.WriteString("or another protocol's own transport.\n\n")
	b.WriteString("| Method | Path | Contract |\n|---|---|---|\n")
	for _, r := range g.contract.Routes {
		contract := "—"
		for _, e := range g.contract.Endpoints {
			if e.Method == r.Method && e.Path == r.Pattern {
				contract = fmt.Sprintf("typed (%s)", e.ResponseKind)
				break
			}
		}
		if strings.HasPrefix(r.Pattern, "/api/ws/") {
			contract = "WebSocket channel"
		}
		b.WriteString(fmt.Sprintf("| `%s` | `%s` | %s |\n", r.Method, r.Pattern, contract))
	}
	b.WriteString("\n")
}

// cell flattens prose into one table cell: newlines close a row in a Markdown
// table and a pipe opens a column, so both have to go.
func (g *Generator) cell(s string) string {
	return strings.ReplaceAll(g.oneLine(s), "|", "\\|")
}

// oneLine collapses a comment's line breaks and runs of whitespace into single
// spaces — what a table cell, or a one-line JS comment, can hold.
func (g *Generator) oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
