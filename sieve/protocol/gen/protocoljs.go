package gen

import (
	"fmt"
	"strings"

	"sieve/sieve/protocol"
)

// ProtocolJS renders the browser half's copy of the vocabulary: the subprotocol
// both wires are dialled with, the frame words each wire speaks, the
// invalidation topics, the command words that ride the command frame as data,
// and the served-asset URL shape.
//
// It exists so the two halves of every wire word have ONE origin. A JS literal
// is a second declaration of a contract Go owns, and its failure mode is silence
// — a frame nobody dispatches and nobody reports.
func (g *Generator) ProtocolJS() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// @ts-check\n")
	b.WriteString(fmt.Sprintf("// GENERATED by %s from sieve/protocol — do not edit.\n", generatedBy))
	b.WriteString("// Change the Go declaration and run `go generate ./sieve/protocol`.\n")
	b.WriteString("//\n")
	b.WriteString("// Every value here is one half of a contract whose other half is Go. Spelling a\n")
	b.WriteString("// frame word as a literal anywhere else re-declares that contract, and a\n")
	b.WriteString("// re-declaration that drifts fails silently: the frame is simply never handled.\n\n")

	g.writeWSSubprotocol(&b)
	for _, channel := range g.contract.Channels() {
		if err := g.writeFrameConstants(&b, channel); err != nil {
			return nil, err
		}
	}
	g.writeTopicConstants(&b)
	g.writeFeatureConstants(&b)
	g.writeCommandConstants(&b)
	g.writeAssetBuilder(&b)

	return []byte(b.String()), nil
}

func (g *Generator) writeWSSubprotocol(b *strings.Builder) {
	if g.contract.WSSubprotocol == "" {
		return
	}
	b.WriteString("/**\n")
	if doc := g.docs.ConstValue(g.contract.DeclaredIn, g.contract.WSSubprotocol); doc != "" {
		for _, line := range strings.Split(doc, "\n") {
			b.WriteString(strings.TrimRight(" * "+line, " "))
			b.WriteString("\n")
		}
	}
	b.WriteString(" * @type {string}\n")
	b.WriteString(" */\n")
	b.WriteString(fmt.Sprintf("export const WS_SUBPROTOCOL = '%s'\n\n", g.contract.WSSubprotocol))
}

func (g *Generator) writeFrameConstants(b *strings.Builder, channel protocol.Channel) error {
	address, err := g.contract.ChannelAddress(channel)
	if err != nil {
		return err
	}
	name := g.jsExportName(string(channel)) + "Frame"
	b.WriteString(fmt.Sprintf("/** Frame type words the %s channel (`%s`) carries. */\n", channel, address))
	b.WriteString(fmt.Sprintf("export const %s = Object.freeze({\n", name))
	// A word that travelled both ways would be ONE constant: the identifier names
	// the word, and which way it is going is a property of the moment it is sent,
	// not of the vocabulary.
	seen := map[string]bool{}
	for _, direction := range g.contract.Directions() {
		var lines []string
		for _, f := range g.contract.FramesFor(channel, direction) {
			if seen[f.Type] {
				continue
			}
			seen[f.Type] = true
			lines = append(lines, fmt.Sprintf("  %s: '%s',\n", g.jsConstantName(f.Type), f.Type))
		}
		if len(lines) == 0 {
			continue
		}
		b.WriteString(fmt.Sprintf("  // %s\n", strings.ToLower(g.directionTitle(direction))))
		for _, line := range lines {
			b.WriteString(line)
		}
	}
	b.WriteString("})\n")
	b.WriteString(fmt.Sprintf("/** @typedef {typeof %s[keyof typeof %s]} %sWord */\n\n", name, name, name))
	return nil
}

func (g *Generator) writeTopicConstants(b *strings.Builder) {
	if len(g.contract.Topics) == 0 {
		return
	}
	b.WriteString("/** Subjects an `invalidate` frame names. A reconnecting client resyncs all of them. */\n")
	b.WriteString("export const Topic = Object.freeze({\n")
	for _, t := range g.contract.Topics {
		if doc := g.docs.ConstValue(g.contract.DeclaredIn, string(t)); doc != "" {
			b.WriteString(fmt.Sprintf("  // %s\n", g.oneLine(doc)))
		}
		b.WriteString(fmt.Sprintf("  %s: '%s',\n", g.jsConstantName(string(t)), t))
	}
	b.WriteString("})\n")
	b.WriteString("/** @typedef {typeof Topic[keyof typeof Topic]} TopicName */\n\n")
	b.WriteString("/** Every topic, for the blanket resync a client runs when its workspace socket reconnects. */\n")
	b.WriteString("export const AllTopics = Object.freeze(Object.values(Topic))\n\n")
}

// writeFeatureConstants publishes the text-service vocabulary: the word each
// registered producer answers to. A feature rides the control frame and the
// marks push as DATA — a new producer is not a new frame type — so this is the
// only place the browser half learns which producers exist.
func (g *Generator) writeFeatureConstants(b *strings.Builder) {
	if len(g.contract.Features) == 0 {
		return
	}
	b.WriteString("/** Text-service producers. A `feature-control` frame names one; a `text-marks` push carries the one that found them. */\n")
	b.WriteString("export const Feature = Object.freeze({\n")
	for _, f := range g.contract.Features {
		b.WriteString(fmt.Sprintf("  %s: '%s',\n", g.jsConstantName(f), f))
	}
	b.WriteString("})\n")
	b.WriteString("/** @typedef {typeof Feature[keyof typeof Feature]} FeatureName */\n\n")
}

// writeCommandConstants publishes the whole registered command vocabulary: the
// families, and every verb keyed under the family it belongs to. Both halves are
// emitted because a `command` frame carries both — the dispatcher rejects a verb
// invoked under a family that is not its own — so a client that reads the verb
// from here reads its family from beside it and cannot pair them wrongly.
func (g *Generator) writeCommandConstants(b *strings.Builder) {
	families := g.contract.CommandFamilies()
	if len(families) == 0 {
		return
	}

	b.WriteString("/** Command families — the namespace a `command` frame declares it is invoking within. */\n")
	b.WriteString("export const CommandFamily = Object.freeze({\n")
	for _, f := range families {
		b.WriteString(fmt.Sprintf("  %s: '%s',\n", g.jsConstantName(f), f))
	}
	b.WriteString("})\n")
	b.WriteString("/** @typedef {typeof CommandFamily[keyof typeof CommandFamily]} CommandFamilyName */\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Every registered verb, under the family it is invoked within. Commands ride\n")
	b.WriteString(" * the `command` frame as DATA — a new command is not a new frame type — so this\n")
	b.WriteString(" * is the only place the browser half learns which verbs exist.\n")
	b.WriteString(" *\n")
	b.WriteString(" * Keyed by the family's WIRE word, so `CommandWords[CommandFamily.AI]` reads.\n")
	b.WriteString(" */\n")
	b.WriteString("export const CommandWords = Object.freeze({\n")
	for _, f := range families {
		b.WriteString(fmt.Sprintf("  '%s': Object.freeze({\n", f))
		for _, c := range g.contract.CommandsIn(f) {
			if c.Description != "" {
				b.WriteString(fmt.Sprintf("    // %s\n", g.oneLine(c.Description)))
			}
			b.WriteString(fmt.Sprintf("    %s: '%s',\n", g.jsConstantName(c.Name), c.Name))
		}
		b.WriteString("  }),\n")
	}
	b.WriteString("})\n\n")
}

func (g *Generator) writeAssetBuilder(b *strings.Builder) {
	if g.contract.AssetURLPrefix == "" {
		return
	}
	b.WriteString("/** The route prefix a document's stored assets are served under. */\n")
	b.WriteString(fmt.Sprintf("export const ASSET_URL_PREFIX = '%s'\n\n", g.contract.AssetURLPrefix))
	b.WriteString("/**\n")
	b.WriteString(" * Builds the served URL of an asset. It is the ONE place the browser half\n")
	b.WriteString(" * concatenates this shape, and the prefix comes from the same Go constant the\n")
	b.WriteString(" * store mints asset references with — so what is written into a document and what\n")
	b.WriteString(" * is requested for it cannot disagree.\n")
	b.WriteString(" * @param {string} uuid the document holding the asset\n")
	b.WriteString(" * @param {string} filename the asset's name within it\n")
	b.WriteString(" * @returns {string}\n")
	b.WriteString(" */\n")
	b.WriteString("export function assetUrl(uuid, filename) {\n")
	b.WriteString("  return `${ASSET_URL_PREFIX}${uuid}/${filename}`\n")
	b.WriteString("}\n")
}

// jsConstantName turns a wire word into the SCREAMING_SNAKE identifier JS
// spells a constant with. The VALUE stays the wire word — the identifier is
// only how the module is read.
func (g *Generator) jsConstantName(word string) string {
	return strings.ToUpper(strings.NewReplacer("-", "_", ".", "_", "/", "_").Replace(word))
}

// jsExportName capitalises a name for an exported binding.
func (g *Generator) jsExportName(word string) string {
	if word == "" {
		return word
	}
	return strings.ToUpper(word[:1]) + word[1:]
}
